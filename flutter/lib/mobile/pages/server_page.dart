void androidChannelInit() {
  gFFI.setMethodCallHandler((method, arguments) {
    debugPrint("flutter got android msg,$method,$arguments");
    try {
      switch (method) {
        case "start_capture":
          {
            gFFI.dialogManager.dismissAll();
            gFFI.serverModel.updateClientState();
            break;
          }
        case "on_state_changed":
          {
            var name = arguments["name"] as String;
            var value = arguments["value"] as String == "true";
            debugPrint("from jvm:on_state_changed,$name:$value");
            gFFI.serverModel.changeStatue(name, value);
            break;
          }
        case "on_android_permission_result":
          {
            var type = arguments["type"] as String;
            var result = arguments["result"] as bool;
            AndroidPermissionManager.complete(type, result);
            break;
          }
        case "on_media_projection_canceled":
          {
            gFFI.serverModel.stopService();
            break;
          }
        case "msgbox":
          {
            var type = arguments["type"] as String;
            var title = arguments["title"] as String;
            var text = arguments["text"] as String;
            var link = (arguments["link"] ?? '') as String;
            msgBox(gFFI.sessionId, type, title, text, link, gFFI.dialogManager);
            break;
          }
        case "stop_service":
          {
            print(
                "stop_service by kotlin, isStart:${gFFI.serverModel.isStart}");
            if (gFFI.serverModel.isStart) {
              gFFI.serverModel.stopService();
            }
            break;
          }
        // Waldlust(DSK-02 — 결정 D40): 도우미 설치 결과(WaldHelper.kt) — 홈 '자동 복구' 카드를 다시 읽는다.
        case "wald_helper_changed":
          {
            final event = arguments["event"] as String;
            if (event == "installed") {
              showToast(translate("wald-helper-installed-toast"));
            } else if (event == "failed") {
              showToast(translate("wald-helper-install-failed-tip"));
            } else if (event == "blocked") {
              showToast(translate("wald-helper-install-blocked-tip"),
                  timeout: const Duration(seconds: 10));
            }
            waldHelperChanged.value++;
            break;
          }
        // Waldlust(DSK-01 — 결정 D44): 앱 안 업데이트 설치 결과(WaldSelfUpdate.kt). 실패는 Rust 상태로 넘겨 진행 창이 오류를 보인다.
        case "wald_self_update_changed":
          {
            final event = arguments["event"] as String;
            final message = arguments["message"] as String? ?? '';
            if (event != "confirm") {
              bind.mainSetCommon(
                  key: 'wald-update-fail',
                  value: '${event == "storage" ? "space" : event}:$message');
            }
            break;
          }
      }
    } catch (e) {
      debugPrintStack(label: "MethodCallHandler err:$e");
    }
    return "";
  });
}

